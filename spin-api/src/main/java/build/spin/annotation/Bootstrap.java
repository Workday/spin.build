import build.spin.Engine;
import build.spin.Service;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Inherited;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Indicates to an {@link Engine} that a {@link Service.MetaClass} (and thus associated the {@link Service})
 * is part of {@link Engine} bootstrapping and should be established before non-{@link Bootstrap} annotated
 * {@link Service.MetaClass}es.
 */
@Documented
@Inherited
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface Bootstrap {

}
